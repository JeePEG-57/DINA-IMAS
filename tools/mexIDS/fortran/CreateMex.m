function CreateMex(MyPath)

if nargin == 1
    MyPath = [MyPath '/'];
else
    MyPath = '';
end

FFLAGS = ['FFLAGS=\$FFLAGS' ...
    ' -fdefault-real-8 -fPIC -fno-second-underscore -ffree-line-length-none' ...
    ' -I$UAL/fortraninterface/amd64_gfortran'];

LDFLAGS = ['LDFLAGS=\$LDFLAGS' ...
    ' -L$UAL/fortraninterface -lUALFORTRANInterface_gfortran' ...
    ' -L$UAL/lowlevel -lUALLowLevel' ...
    ' -Wl -lm'];

mex('-v', '-g', 'FC=gfortran', ...
    FFLAGS, ...
    'FOPTIMFLAGS=-O0', ...
    'FDEBUGFLAGS=-g', ...
    LDFLAGS, ...
    'LDOPTIMFLAGS= ',...
    'LDDEBUGFLAGS= ',...
    [MyPath 'mexLoadIDS.F90'], [MyPath 'mexFillIDSUtil.F90'], ...
    [MyPath 'mexFillEquilibrium.F90'], [MyPath 'mexFillPFActive.F90'], ...
    [MyPath 'mexFillPFPassive.F90'], [MyPath 'mexFillCoreProfiles.F90']);

end